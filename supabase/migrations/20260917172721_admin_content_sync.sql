-- Durable Admin Content Operations contract.
--
-- The static Admin editor currently owns a richer content shape than the
-- canonical MVP tables (deck-specific cards, assets, and front-end blocks).
-- Keep that shape intact in an immutable, versioned bundle while the normal
-- tables remain the runtime source for the already-migrated backend features.

create table if not exists public.admin_content_bundles (
  id uuid primary key default gen_random_uuid(),
  bundle_key text not null default 'nilaza_default'
    check (bundle_key ~ '^[a-z0-9][a-z0-9_-]{0,63}$'),
  version bigint generated by default as identity,
  schema_version integer not null default 4
    check (schema_version between 1 and 10),
  source_version text not null,
  payload jsonb not null
    check (
      jsonb_typeof(payload) = 'object'
      and jsonb_typeof(payload -> 'personas') = 'array'
      and jsonb_typeof(payload -> 'decks') = 'array'
      and jsonb_typeof(payload -> 'cards') = 'array'
      and jsonb_typeof(payload -> 'assets') = 'array'
      and jsonb_typeof(payload -> 'frontendContent') = 'array'
    ),
  status text not null default 'draft'
    check (status in ('draft', 'review', 'published', 'archived')),
  base_published_version bigint,
  created_by uuid not null references auth.users(id) on delete restrict,
  updated_by uuid not null references auth.users(id) on delete restrict,
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  supersedes_id uuid references public.admin_content_bundles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists admin_content_bundles_one_published_idx
  on public.admin_content_bundles(bundle_key)
  where status = 'published';

create index if not exists admin_content_bundles_lookup_idx
  on public.admin_content_bundles(bundle_key, status, version desc);

create table if not exists public.admin_content_bundle_events (
  id bigint generated by default as identity primary key,
  bundle_id uuid references public.admin_content_bundles(id) on delete set null,
  bundle_key text not null,
  action text not null check (action in ('draft_saved', 'published', 'rolled_back')),
  actor_id uuid not null references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_content_bundle_events_lookup_idx
  on public.admin_content_bundle_events(bundle_key, created_at desc);

alter table public.admin_content_bundles enable row level security;
alter table public.admin_content_bundle_events enable row level security;

revoke all on table public.admin_content_bundles, public.admin_content_bundle_events from anon;
grant select, insert, update, delete on table public.admin_content_bundles to authenticated;
grant select, insert on table public.admin_content_bundle_events to authenticated;

drop policy if exists "published content bundles are readable" on public.admin_content_bundles;
create policy "published content bundles are readable"
  on public.admin_content_bundles for select to authenticated
  using (
    status = 'published'
    or (select nilaza_private.has_capability('content.read'))
  );

drop policy if exists "content editors create drafts" on public.admin_content_bundles;
create policy "content editors create drafts"
  on public.admin_content_bundles for insert to authenticated
  with check (
    (select nilaza_private.has_capability('content.draft'))
    and created_by = (select auth.uid())
    and updated_by = (select auth.uid())
    and status in ('draft', 'review')
  );

drop policy if exists "content editors update drafts" on public.admin_content_bundles;
create policy "content editors update drafts"
  on public.admin_content_bundles for update to authenticated
  using (
    (select nilaza_private.has_capability('content.draft'))
    and status in ('draft', 'review')
  )
  with check (
    (select nilaza_private.has_capability('content.draft'))
    and status in ('draft', 'review')
    and updated_by = (select auth.uid())
  );

drop policy if exists "content publishers release bundles" on public.admin_content_bundles;
create policy "content publishers release bundles"
  on public.admin_content_bundles for update to authenticated
  using (
    (select nilaza_private.has_capability('content.publish'))
    and status in ('draft', 'review', 'published', 'archived')
  )
  with check (
    (select nilaza_private.has_capability('content.publish'))
    and status in ('draft', 'review', 'published', 'archived')
  );

drop policy if exists "content owners delete drafts" on public.admin_content_bundles;
create policy "content owners delete drafts"
  on public.admin_content_bundles for delete to authenticated
  using (
    status in ('draft', 'review')
    and (select nilaza_private.has_capability('content.delete'))
  );

drop policy if exists "content staff read bundle events" on public.admin_content_bundle_events;
create policy "content staff read bundle events"
  on public.admin_content_bundle_events for select to authenticated
  using ((select nilaza_private.has_capability('content.read')));

drop policy if exists "content staff write bundle events" on public.admin_content_bundle_events;
create policy "content staff write bundle events"
  on public.admin_content_bundle_events for insert to authenticated
  with check (
    actor_id = (select auth.uid())
    and (select nilaza_private.has_capability('content.publish'))
  );

create or replace function public.get_published_content_bundle(
  p_bundle_key text default 'nilaza_default'
)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'id', id,
    'bundleKey', bundle_key,
    'version', version,
    'schemaVersion', schema_version,
    'sourceVersion', source_version,
    'status', status,
    'publishedAt', published_at,
    'payload', payload
  )
  from public.admin_content_bundles
  where bundle_key = p_bundle_key
    and status = 'published'
  order by version desc
  limit 1;
$$;

create or replace function public.publish_content_bundle(
  p_bundle_id uuid,
  p_expected_published_version bigint default null
)
returns jsonb
language plpgsql
volatile
security invoker
set search_path = ''
as $$
declare
  candidate public.admin_content_bundles%rowtype;
  current_published public.admin_content_bundles%rowtype;
begin
  if auth.uid() is null or not nilaza_private.has_capability('content.publish') then
    raise exception 'Not authorized' using errcode = '42501';
  end if;

  select * into candidate
  from public.admin_content_bundles
  where id = p_bundle_id
  for update;

  if candidate.id is null or candidate.status not in ('draft', 'review', 'archived') then
    raise exception 'Bundle is not publishable' using errcode = '22023';
  end if;

  select * into current_published
  from public.admin_content_bundles
  where bundle_key = candidate.bundle_key and status = 'published'
  for update;

  if p_expected_published_version is not null
     and (current_published.id is null or current_published.version <> p_expected_published_version) then
    raise exception 'Published content changed; reload before publishing' using errcode = '40001';
  end if;

  if current_published.id is not null then
    update public.admin_content_bundles
      set status = 'archived', updated_at = now()
      where id = current_published.id;
  end if;

  update public.admin_content_bundles
    set status = 'published',
        published_by = auth.uid(),
        published_at = now(),
        supersedes_id = current_published.id,
        updated_by = auth.uid(),
        updated_at = now()
    where id = candidate.id;

  insert into public.admin_content_bundle_events(bundle_id, bundle_key, action, actor_id, metadata)
    values (
      candidate.id,
      candidate.bundle_key,
      case when candidate.status = 'archived' then 'rolled_back' else 'published' end,
      auth.uid(),
      jsonb_build_object(
        'version', candidate.version,
        'previousVersion', current_published.version,
        'sourceVersion', candidate.source_version
      )
    );

  return jsonb_build_object(
    'id', candidate.id,
    'bundleKey', candidate.bundle_key,
    'version', candidate.version,
    'status', 'published',
    'previousVersion', current_published.version
  );
end;
$$;

revoke all on function public.get_published_content_bundle(text) from public, anon;
grant execute on function public.get_published_content_bundle(text) to authenticated;
revoke all on function public.publish_content_bundle(uuid, bigint) from public, anon;
grant execute on function public.publish_content_bundle(uuid, bigint) to authenticated;


